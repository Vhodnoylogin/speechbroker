#pragma once

#include <cstddef>
#include <cstdint>
#include <string>

namespace Envoy
{
	struct Utterance;

	// Придержать реплику или отдать её сразу.
	//
	// Смысл придержания в том, чтобы НИКТО не начал действовать, пока не ясно,
	// кончилась ли фраза. Поэтому решение принимается один раз для реплики,
	// а не отдельно для каждого подписчика: схема, где нетерпеливые получают
	// обрывок, а требовательные ждут, разрешает ровно то, ради предотвращения
	// чего придержание и заведено. Действие по «Закрой дверь», когда сказано
	// было «Закрой дверь когда будешь уходить», остаётся ошибкой независимо
	// от того, кто именно его совершил.
	//
	// Границы в коде нет и в настройках нет. Она считается от того, кто сейчас
	// в зале: сколько подписчиков услышали бы эту фразу и какого они рода.
	// Один отзывчивый с обратимым действием и пятеро с дорогими необратимыми -
	// разная цена ошибки, и одинаковый порог для них означал бы, что в одном
	// случае мы тормозим зря, а в другом зря рискуем. Настраивается ДОПУСК -
	// сколько риска мы согласны терпеть, - а порог получается сам.
	class Hold
	{
	public:
		struct Decision
		{
			bool         hold{ false };
			float        damage{ 0.0f };   // цена ошибки, сложенная по всему залу
			float        risk{ 0.0f };     // (1 - завершённость) * ущерб
			std::size_t  audience{ 0 };    // сколько подписчиков узнали фразу
			std::int32_t ceilingMs{ 0 };   // дольше этого не держим ни при чём
			std::string  reason;
		};

		// Зовётся из главного потока: смотрит на тему, а тема - на состояние игры.
		static Decision Judge(const Utterance& a_utterance);
	};
}
