#pragma once

#include <functional>

namespace Envoy
{
	// Шов «выполнить там, где это безопасно».
	//
	// Ядру нужно ровно одно: положить работу в тот поток, где её можно делать.
	// Что это за поток - дело того, кто ядро завёл. В игре его даёт SKSE своим
	// интерфейсом задач; хост проверки ставит очередь и вычерпывает её сам
	// между своими шагами, потому что «на месте вызова» для потолка
	// придержания означало бы «в потоке планировщика», параллельно с приёмом
	// следующей реплики. Без диспетчера вовсе работа делается на месте.
	//
	// Раньше ядро звало SKSE::GetTaskInterface напрямую, и одна эта строка
	// делала аукцион непригодным к запуску без игры.
	class MainThread
	{
	public:
		using Task = std::function<void()>;

		// Кто умеет доставить работу в главный поток.
		class Dispatcher
		{
		public:
			virtual ~Dispatcher() = default;
			virtual void Post(Task a_task) = 0;
		};

		// Без установленного диспетчера работа выполняется прямо здесь - в том
		// потоке, откуда позвали. Для одного потока это строго определённый
		// порядок; тому, у кого потоков больше одного, полагается поставить
		// диспетчер, как это делает хост проверки.
		static void Install(Dispatcher* a_dispatcher);
		static void Post(Task a_task);
	};
}
